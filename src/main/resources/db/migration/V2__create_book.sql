CREATE TABLE book (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title        VARCHAR(200)             NOT NULL,
    isbn         VARCHAR(17),
    published_on DATE,
    pages        INTEGER,
    author_id    BIGINT                   NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    version      BIGINT                   NOT NULL,
    CONSTRAINT pk_book PRIMARY KEY (id),
    CONSTRAINT uk_book_isbn UNIQUE (isbn),
    CONSTRAINT fk_book_author FOREIGN KEY (author_id) REFERENCES author (id) ON DELETE RESTRICT,
    CONSTRAINT ck_book_isbn_length CHECK (char_length(isbn) BETWEEN 10 AND 17),
    CONSTRAINT ck_book_pages CHECK (pages >= 1)
);

CREATE INDEX ix_book_author_id ON book (author_id);
